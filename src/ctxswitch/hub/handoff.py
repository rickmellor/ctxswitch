"""Handoff: continue a session's work in a different agent (Claude Code -> Antigravity, pi -> Claude, …).

No agent resumes another's transcript, so the hub renders what it knows about the session into one markdown
document, the client writes it to a file, and the new agent is started with an opening prompt that points at it.
The prompt carries a marker, ``[ctxswitch-handoff:<key>]``; when the new session's first turn reaches the hub,
upsert_turns sees it and links the two (store.link_handoff), so the ledger's standing instructions and the
purpose carry over and both sessions show the link.
"""
from __future__ import annotations

import re
from datetime import datetime, timezone
from typing import Any

MARK = "[ctxswitch-handoff:{key}]"
MARK_RE = re.compile(r"\[ctxswitch-handoff:([^\]\s]+)\]")
NAMES = {"claude": "Claude Code", "pi": "pi", "claude-win": "Claude Code (Windows)", "agy": "Google Antigravity"}
BRIEF_TURNS = 3


def marker_in(text: str | None) -> str | None:
    """The key a handoff prompt names, if ``text`` is one."""
    m = MARK_RE.search(text or "")
    return m.group(1) if m else None


def _when(s: str | None) -> str:
    try:
        return datetime.fromisoformat(str(s).replace("Z", "+00:00")).astimezone().strftime("%Y-%m-%d %H:%M")
    except ValueError:
        return s or ""


def render(s: dict[str, Any], to: str | None = None, full: bool = True, now: datetime | None = None) -> str:
    """The handoff document for one store.session() dict (turns newest-last, as session() returns them)."""
    now = now or datetime.now(timezone.utc)
    frm = NAMES.get(s.get("harness", ""), s.get("harness", ""))
    title = s.get("title") or s.get("key")
    out = [f"# Handoff: {title}", "",
           f"This work was being done in a {frm} session (`{s.get('key')}`) on {s.get('host_id')}"
           + (f" and continues in {NAMES.get(to, to)}" if to else "") + f". Written {now.astimezone().strftime('%Y-%m-%d %H:%M')}.",
           f"Working directory: `{s.get('cwd') or '?'}`" + (f", repo `{s['repo_remote']}`" if s.get("repo_remote") else "")
           + (f" on branch `{s['git_branch']}`" if s.get("git_branch") else "") + ".", ""]
    if s.get("purpose"):
        out += ["## What this work is for", "", s["purpose"], ""]
    rules = [r for r in s.get("ledger") or [] if r.get("kind") == "instruction" and r.get("active")]
    if rules:
        out += ["## Standing instructions from the operator (still in force)", ""]
        out += [f"- {r['text']}" + (f'  ("{r["quote"]}")' if r.get("quote") and r["quote"] != r["text"] else "") for r in rules] + [""]
    decisions = [r for r in s.get("ledger") or [] if r.get("kind") == "decision" and r.get("active")]
    if decisions:
        out += ["## Decisions the operator made", ""] + [f"- {r['text']}" for r in decisions] + [""]
    claims = [r for r in s.get("ledger") or [] if r.get("kind") == "claim" and r.get("active")]
    if claims:
        out += ["## What the previous agent reported", ""] + [f"- {r['text']}" for r in claims] + [""]
    if s.get("recap"):
        out += ["## Where it stood", "", s["recap"], ""]
    opens = [a for a in s.get("asks") or [] if not a.get("answered")]
    if opens:
        out += ["## Questions still open", ""] + [f"- {a.get('text')}" for a in opens] + [""]
    turns = [t for t in s.get("turns") or [] if t.get("user_text") or t.get("assistant_text")]
    shown = turns if full else turns[-BRIEF_TURNS:]
    if shown:
        head = "## The conversation" if full else f"## The last {len(shown)} exchanges"
        out += [head + f" ({len(turns)} exchange{'s' if len(turns) != 1 else ''} in all)", ""]
        for t in shown:
            out.append(f"### {t.get('idx', 0) + 1} · {_when(t.get('started_at'))}")
            if t.get("user_text"):
                who = "Operator" if t.get("user_origin") in (None, "human") else f"Input ({t.get('user_origin')})"
                out += ["", f"**{who}:** {t['user_text'].strip()}"]
            tally = t.get("tally") or {}
            used = ", ".join(f"{v} {k}" for k, v in tally.items() if v and k != "errors")
            if t.get("assistant_text"):
                out += ["", f"**Agent:** {t['assistant_text'].strip()}"]
            if used:
                out += ["", f"_Tools: {used}_"]
            out.append("")
    out += ["---", "", f"Generated by ctxswitch. The session key above identifies the original; the operator can `ctx show {s.get('key')}` for more."]
    return "\n".join(out)


def prompt(path: str, s: dict[str, Any], to: str | None = None) -> str:
    """The opening prompt for the new agent. Short: the document does the work."""
    frm = NAMES.get(s.get("harness", ""), s.get("harness", ""))
    return (f"You are taking over work from a {frm} session. Read {path} first: it holds what the work is for, the "
            f"operator's standing instructions, the decisions made, what the previous agent reported, and the conversation so "
            f"far. Then carry on from where it left off in this directory. Keep the standing instructions. Don't redo what it "
            f"reported done without checking. Start by saying in two or three lines what you understand the current state and "
            f"next step to be. {MARK.format(key=s.get('key'))}")
